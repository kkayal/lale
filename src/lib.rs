use pest_derive::Parser;

/// Macro for reporting internal compiler errors with a Lale-style message.
/// Formats the error in red (like other compiler errors) and panics.
/// In debug builds, appends the Rust source location.
///
/// # Usage
///
/// ```ignore
/// ice!("struct '{}' field {} offset unknown", name, index);
/// ice!("{} should be unreachable", description);
/// ```
/// Shared helper: formats an internal compiler error message with debug location.
#[macro_export]
macro_rules! internal_error {
  ($($arg:tt)*) => {{
    let mut msg = format!("internal compiler error: {}", format_args!($($arg)*));
    if cfg!(debug_assertions) {
      msg.push_str(&format!("\n  (Rust: {}:{})", file!(), line!()));
    }
    msg
  }};
}

/// Macro for reporting internal compiler errors.
/// Prints the error in red bold and exits — works in any context.
#[macro_export]
macro_rules! ice {
  ($($arg:tt)*) => {{
    use colored::Colorize;
    let msg = $crate::internal_error!($($arg)*);
    eprintln!("{}", msg.red().bold());
    std::process::exit(1);
  }};
}

